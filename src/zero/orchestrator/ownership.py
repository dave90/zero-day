"""Advisory cross-process ownership shared by terminal and headless runtimes."""
from __future__ import annotations

import fcntl
import os
from pathlib import Path


class WorkspaceOwnership:
    def __init__(self, cwd: Path) -> None:
        self.path = cwd / ".zero-runtime.lock"
        self.handle = None

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.handle = self.path.open("a+")
        try:
            fcntl.flock(self.handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            self.handle.close()
            raise RuntimeError("Engagement directory is already in use by another runtime") from None
        self.handle.seek(0)
        self.handle.truncate()
        self.handle.write(str(os.getpid()))
        self.handle.flush()
        return self

    def __exit__(self, *_):
        if self.handle is not None:
            fcntl.flock(self.handle.fileno(), fcntl.LOCK_UN)
            self.handle.close()
